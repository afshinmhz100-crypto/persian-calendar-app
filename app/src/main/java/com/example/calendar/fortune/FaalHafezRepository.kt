    /**
     * Gets a deterministic daily fortune based on today's Persian day of year,
     * ensuring the daily horoscope stays consistent throughout the day.
     */
    fun getDailyFortune(): FaalItem {
        val calendar = Calendar.getInstance()
        val dayOfYear = calendar.get(Calendar.DAY_OF_YEAR)
        val index = dayOfYear % HAFEZ_FAAL_LIST.size
        return HAFEZ_FAAL_LIST[index]
    }

    /**
     * Takes a new random divination (تفال جدید).
     */
    fun getRandomFortune(excludeId: Int = -1): FaalItem {
        val candidates = HAFEZ_FAAL_LIST.filter { it.id != excludeId }
        return candidates[Random.nextInt(candidates.size)]
    }

    fun getAllFortunes(): List<FaalItem> = HAFEZ_FAAL_LIST
